import assert from 'node:assert/strict'
import { checkIsland } from './island-db.mjs'

export async function checkSharedPlay(db, asUser, A, B, C) {
  const q = async (sql,args=[]) => (await db.query(sql,args)).rows
  await db.query('delete from public.blocks')
  await db.query('delete from public.friendships')
  await db.query("insert into public.friendships(user_a,user_b,requested_by,status) values($1,$2,$1,'accepted')",[A,B])
  const create = (user, game, body, id=crypto.randomUUID()) => asUser(user,async () => (await q('select public.shared_play_create($1,$2,$3,$4) id',[user===A?B:A,game,body,id]))[0].id)
  const list = user => asUser(user,async () => (await q('select public.shared_play_list($1) rows',[user===A?B:A]))[0].rows)
  const act = (user,id,revision,action,value='',request=crypto.randomUUID()) => asUser(user,()=>q('select public.shared_play_act($1,$2,$3,$4,$5)',[id,revision,action,value,request]))
  const id=await create(A,'pick',{prompt:'An evening?',a:'Movie',b:'Walk',answer:'b'})
  assert.equal(await create(A,'pick',{prompt:'ignored'},id),id,'creation retry is idempotent')
  assert.equal((await list(B))[0].secret,undefined,'secret is never returned')
  assert.equal((await list(A))[0].secret,undefined)
  await asUser(C,()=>assert.rejects(q('select public.shared_play_list($1)',[A])))
  await asUser(C,()=>assert.rejects(q('select public.shared_play_create($1,$2,$3,$4)',[A,'date',{text:'stranger'},crypto.randomUUID()])))
  await asUser(C,()=>assert.rejects(q('select public.shared_play_act($1,0,$2,$3,$4)',[id,'dismiss','',crypto.randomUUID()])))
  await asUser(B,()=>assert.rejects(q('select secret from public.shared_play')))
  await assert.rejects(act(A,id,0,'accept'))
  await assert.rejects(act(B,id,0,'move','b'))
  await act(B,id,0,'accept')
  await assert.rejects(act(B,id,null,'move','b'))
  await assert.rejects(act(A,id,1,'move','b'))
  await assert.rejects(act(B,id,0,'move','b'))
  const retry=crypto.randomUUID()
  await act(B,id,1,'move','b',retry)
  await act(B,id,1,'move','b',retry)
  assert.equal((await list(A))[0].data.correct,true)
  assert.equal((await list(A))[0].revision,2)
  const word=await create(A,'word',{text:'spark'})
  await act(B,word,0,'accept')
  await assert.rejects(act(B,word,1,'move','apple'))
  await act(B,word,1,'move','kite')
  await assert.rejects(act(B,word,2,'move','egg'))
  await act(A,word,2,'move','eggs')
  await assert.rejects(act(B,word,3,'move','spark'))
  const story=await create(A,'story',{text:'A dragon arrived.'})
  await act(B,story,0,'accept')
  for(let i=1;i<8;i++) await act(i%2?B:A,story,i,'move',`Sentence ${i}`)
  assert.equal((await list(A)).find(row=>row.id===story).status,'done')
  await assert.rejects(act(A,story,8,'move','one more'))
  const emoji=await create(A,'emoji',{prompt:'🍕',answer:'Pizza'})
  await act(B,emoji,0,'accept'); await act(B,emoji,1,'move',' pizza ')
  assert.equal((await list(B)).find(row=>row.id===emoji).data.correct,true)
  const date=await create(B,'date',{text:'A picnic'})
  await act(A,date,0,'interest')
  assert.equal((await list(B)).find(row=>row.id===date).data.likes.length,2)
  await checkIsland(db,asUser,A,B,C)
  await assert.rejects(asUser(A,()=>q('select get_call_ice($1)',[B])),'missing relay fails explicitly')
  await db.query("insert into call_relay_config(ice_servers) values('[{\"urls\":\"turn:example.invalid\",\"username\":\"test\",\"credential\":\"test\"}]')")
  assert.equal((await asUser(A,()=>q('select get_call_ice($1) config',[B])))[0].config[0].username,'test')
  await asUser(C,()=>assert.rejects(q('select get_call_ice($1)',[A])))
  await asUser(A,()=>assert.rejects(q('select * from call_relay_config')))
  await db.query('update public.shared_play set expires_at=now()-interval \'1 second\' where id=$1',[word])
  await assert.rejects(act(A,word,3,'move','sun'))
  assert.ok(!(await list(A)).find(row=>row.id===word))
  await db.query('insert into public.blocks(blocker,blocked) values($1,$2)',[A,B])
  await assert.rejects(list(B))
  await db.query('select public.purge_shared_play()')
  assert.equal((await q('select count(*)::int n from public.shared_play'))[0].n,0)
  await db.query('delete from public.blocks')
  await create(A,'date',{text:'A tiny adventure'})
  await db.query('delete from public.friendships where user_a=$1 and user_b=$2',[A,B])
  assert.equal((await q('select count(*)::int n from public.shared_play'))[0].n,0,'unfriending immediately removes shared content')
  await db.query('delete from public.locations')
  assert.equal((await asUser(A,()=>q('select refresh_live_location(12,77) ok')))[0].ok,false,'automatic fix cannot create a share')
  await db.query("insert into public.locations(user_id,lat,lng,sharing,expires_at) values($1,12,77,true,now()+interval '1 hour')",[A])
  assert.equal((await asUser(B,()=>q('select refresh_live_location(13,78) ok')))[0].ok,false,'cannot update someone else')
  assert.equal((await asUser(A,()=>q('select refresh_live_location(13,78) ok')))[0].ok,true)
  await db.query("update public.locations set expires_at=now()-interval '1 second' where user_id=$1",[A])
  assert.equal((await asUser(A,()=>q('select refresh_live_location(14,79) ok')))[0].ok,false,'expired sharing cannot be resurrected')
  await db.query('delete from public.locations')
  console.log('PASS shared play: secrets, acceptance, turns, retry, expiry, shared dates and blocked access')
}
